def sim(msg, confirm=None):
    api._uid_cache = {}
    r = api.execute_request(msg)
    if r.startswith("CONFIRM_FUZZY:"):
        name = r.split(":",1)[1].strip()
        q = f"❓ האם התכוונת ל: *{name}*?"
        if confirm == "כן":
            r2 = api.execute_request(msg, force=True, name_override=name)
            return q, r2
        return q, "❌ בוטל" if confirm == "לא" else "(ללא תשובה)"
    if r.startswith("CONFIRM:"):
        summary = r.split(":",1)[1].strip()
        q = f"❓ הבנתי:\n{summary}"
        if confirm == "כן":
            r2 = api.execute_request(msg, force=True)
            return q, r2
        return q, "❌ בוטל" if confirm == "לא" else "(ללא תשובה)"
    return r, None

def tag(r):
    if r is None: return ""
    if r.startswith("✅"): return "✅"
    if r.startswith("❓ האם"): return "🔄FUZZY"
    if r.startswith("❓ הבנתי"): return "🔄CONF"
    if r.startswith("❓"): return "❓ALT"
    if r.startswith("❌"): return "❌"
    if "פורמט" in r or "לא הבנתי" in r: return "⚠️FMT"
    return "ℹ️"

