# ─── helpers ─────────────────────────────────────────────────────────────────
PASS = 0
FAIL = 0
FAILS = []

def chk(label, msg, *, name=None, food=None, hint=None, meal=None,
        grams=None, reduce=None, ops_count=None):
    global PASS, FAIL
    p = parse_message(msg)
    errors = []

    if name is not None:
        got = p.get("name","")
        if name.lower() not in got.lower():
            errors.append(f"name: expected '{name}' in '{got}'")

    if food is not None:
        ch = p.get("change","")
        ops = p.get("ops",[])
        all_ch = ch + " ".join(o.get("change","") for o in ops)
        if food.lower() not in all_ch.lower():
            errors.append(f"food: expected '{food}' in change='{ch}'")

    if hint is not None:
        ch = p.get("change","")
        ops = p.get("ops",[])
        all_ch = ch + " ".join(o.get("change","") for o in ops)
        if hint.lower() not in all_ch.lower():
            errors.append(f"hint: expected '{hint}' in change='{ch}'")

    if meal is not None:
        got = p.get("meal","") or ""
        meals_got = p.get("meals") or ([got] if got else [])
        if not any(meal.lower() in m.lower() for m in meals_got):
            errors.append(f"meal: expected '{meal}' in {meals_got}")

    if grams is not None:
        got = str(p.get("extra_grams") or "")
        ops = p.get("ops",[])
        all_g = got + " ".join(str(o.get("extra_grams","")) for o in ops)
        ch = p.get("change","")
        all_ch = ch + " ".join(o.get("change","") for o in ops)
        # גרמים ב-extra_grams OR בתוך change string (parse_message משאיר אותם שם, execute_request חולץ)
        if str(grams) not in all_g and str(grams) not in all_ch:
            errors.append(f"grams: expected '{grams}' in extra_grams='{got}' or change='{ch}'")

    if reduce is not None:
        got = bool(p.get("reduce"))
        ops = p.get("ops",[])
        got_any = got or any(o.get("reduce") for o in ops)
        if reduce != got_any:
            errors.append(f"reduce: expected {reduce}, got {got_any}")

    if ops_count is not None:
        got = len(p.get("ops", [p] if p.get("change") else []))
        if got != ops_count:
            errors.append(f"ops_count: expected {ops_count}, got {got}")

    if errors:
        FAIL += 1
        FAILS.append((label, msg, errors, p))
        print(f"❌ FAIL [{label}]: {errors}")
    else:
        PASS += 1
        print(f"✅ PASS [{label}]")

