#!/usr/bin/env node
// test_missed_command.js — "פקודה-כמעט" בלי המילה "לך".
//
// רקע (20.7 — ליה אפרים): דני כתב ללקוחה "אני מוסיף כוסמת +בורגול+קינואה כאופציה
// לאורז בארוחת צהריים+ערב" — בלי "לך". הבוט לא זיהה כפקודה (דורש "מוסיף לך"),
// והתעלם *בשקט*: לא ביצע, לא שאל, לא התריע. ליה לא קיבלה שינוי ("עדיין לא רואה").
//
// התיקון: כשההודעה נראית כמו פקודה אבל חסרה "לך" → הבוט *לא מריץ* (ניחוש עלול
// לשנות תפריט לא-נכון) אבל *מתריע* לדני לשלוח שוב עם "לך". התראה לא מקלקלת תפריט.
//
// בדיקה זו על הקוד האמיתי (biz_routing.js): looksLikeMissedCommand + hasTriggerWord.

const { looksLikeMissedCommand, hasTriggerWord, normalizeBizText } = require('./biz_routing');

let PASS = 0, FAIL = 0;
const FAILS = [];
function chk(label, got, expected) {
  const ok = got === expected;
  if (ok) { PASS++; console.log(`  ✅ ${label}`); }
  else { FAIL++; FAILS.push(`${label}\n      ציפי: ${expected}\n      קיבל: ${got}`); console.log(`  ❌ ${label}`); }
}
const missed  = t => looksLikeMissedCommand(normalizeBizText(t));
const trigger = t => hasTriggerWord(normalizeBizText(t));

console.log("═══ A. המקרה שנכשל (ליה אפרים 20.7) — חייב להתריע ═══");
chk("A1 'אני מוסיף X כאופציה לאורז' בלי 'לך' → פקודה-כמעט (מתריע)",
  missed("אני מוסיף כוסמת +בורגול+קינואה כאופציה לאורז בארוחת צהריים+ערב"), true);
chk("A2 ...ואותה הודעה *לא* מזוהה כטריגר רגיל (לכן נבלעה)",
  trigger("אני מוסיף כוסמת +בורגול+קינואה כאופציה לאורז בארוחת צהריים+ערב"), false);
chk("A3 'מוריד 30 גרם אורז' בלי 'לך' → פקודה-כמעט",
  missed("מוריד 30 גרם אורז בצהריים"), true);
chk("A4 'מוסיף 50 גרם שמן זית' בלי 'לך' → פקודה-כמעט",
  missed("אני מוסיף 50 גרם שמן זית בערב"), true);

console.log("═══ B. פקודות אמיתיות עם 'לך' — לא עוברות במסלול-ההתראה ═══");
// עם "לך" hasTriggerWord=true, ולכן הן רצות רגיל ולא מגיעות ל-looksLikeMissedCommand.
chk("B1 'מוסיף לך X כאופציה לאורז' → טריגר אמיתי (מבוצע, לא מותרע)",
  trigger("אני מוסיף לך כוסמת +בורגול+קינואה כאופציה לאורז בצהריים+ערב"), true);
chk("B2 'מוריד לך 30 גרם' → טריגר אמיתי",
  trigger("מוריד לך 30 גרם אורז בצהריים"), true);

console.log("═══ C. מקרי-ביקורת — שיחה רגילה, אסור להתריע ═══");
chk("C1 שאלה ('מה אתה רוצה להוסיף?') → לא מתריע",
  missed("מה אתה רוצה להוסיף?"), false);
chk("C2 על אדם אחר ('אני מוסיף לו עוד שבוע') → לא מתריע",
  missed("אני מוסיף לו עוד שבוע"), false);
chk("C3 תנאי ('אם הוספתי לך זה איכותי') → לא מתריע",
  missed("אם הוספתי לך זה איכותי"), false);
chk("C4 שלילה ('לא מוסיף כלום') → לא מתריע",
  missed("לא מוסיף כלום היום"), false);
chk("C5 תמונה ('אני מעלה תמונה, יש בה 50 גרם אורז') → לא מתריע",
  missed("אני מעלה כאן תמונה יש בה 50 גרם אורז בערב"), false);
chk("C6 שיחה בלי סמן-תפריט ('אני מוסיף אימון') → לא מתריע",
  missed("אני מוסיף אימון מחר"), false);
chk("C7 ברכה רגילה → לא מתריע", missed("בוקר אור אביר!"), false);
chk("C8 שאלה על מזון עם גרם ('אתה מוריד 50 גרם אורז?') → לא מתריע",
  missed("אתה מוריד 50 גרם אורז בערב?"), false);

console.log(`\n═══ סיכום: ${PASS} עברו, ${FAIL} נכשלו ═══`);
if (FAIL) { console.log("\nכשלונות:\n" + FAILS.map(f => "  ❌ " + f).join("\n")); process.exit(1); }
console.log("✅ הכל עבר");
