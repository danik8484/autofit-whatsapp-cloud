# ── normalize tests ───────────────────────────────────────────
NORM_TESTS = [
    ("חזה עוף לפני הבישול", "חזה עוף לפני בישול"),
    ("החזה העוף המבושל",    "חזה עוף מבושל"),
    ("אורז לבן", "אורז לבן"),
    ("חזה עוף לפני בשול",   "חזה עוף לפני בישול"),
    ("אחרי בישול",          "מבושל"),
]


def run_tests():
    issues = []
    print("=" * 70)
    print(f"{'ID':>3}  {'CONF':>4}  {'NAME':<20} {'MEAL':<10} {'CHANGE':<35}")
    print("=" * 70)
    for t in TESTS:
        p = parse_message(t["msg"])
        conf = p.get("confidence", 100)
        name = p.get("name", "—")[:20]
        meal = p.get("meal", "—")[:10]
        change = p.get("change", "—")[:35]
        flag = ""

        # זיהוי בעיות
        if "name" not in p:
            flag = "⚠️ NO NAME"
            issues.append((t["id"], t["desc"], "שם לא זוהה"))
        if "change" not in p:
            flag = "⚠️ NO CHANGE"
            issues.append((t["id"], t["desc"], "פעולה לא זוהתה"))
        if conf < 90 and t["id"] <= 18:  # תבניות מובנות אמורות להיות 100
            flag = f"⚠️ CONF={conf}"
            issues.append((t["id"], t["desc"], f"confidence נמוך ({conf}) לתבנית מובנית"))
        if meal == "—" and t["id"] != 22:
            flag = "⚠️ NO MEAL"

        row = f"{t['id']:>3}  {conf:>4}  {name:<20} {meal:<10} {change:<35}  {flag}"
        print(row)

    # normalize tests
    print("\n── normalize_food_query ──")
    for inp, expected in NORM_TESTS:
        result = normalize_food_query(inp)
        ok = "✅" if result == expected else "❌"
        print(f"  {ok}  '{inp}' → '{result}' (expected: '{expected}')")
        if result != expected:
            issues.append(("norm", inp, f"expected '{expected}', got '{result}'"))

    # סיכום
    print("\n" + "=" * 70)
    print(f"סה\"כ בעיות שנמצאו: {len(issues)}")
    for issue_id, desc, problem in issues:
        print(f"  #{issue_id}: {desc}")
        print(f"      → {problem}")
    return issues


if __name__ == "__main__":
    run_tests()
